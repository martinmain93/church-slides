/**
 * Build the online relay: the band page (one JS + one CSS file) embedded in a
 * single-module Worker, `relay/dist/worker.js`. The desktop app bundles that
 * file and uploads it to the church's Cloudflare account.
 *
 *   node scripts/build_relay.mjs
 */
import { build as viteBuild } from "vite";
import { build as esbuild } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const relay = path.join(root, "relay");

await viteBuild({ configFile: path.join(relay, "vite.band.config.ts"), logLevel: "warn" });
const js = readFileSync(path.join(relay, "dist/band/band.js"), "utf8");
const css = readFileSync(path.join(relay, "dist/band/band.css"), "utf8");
writeFileSync(
  path.join(relay, "src/assets.ts"),
  `// Generated by scripts/build_relay.mjs — do not edit.\nexport const BAND_JS = ${JSON.stringify(js)};\nexport const BAND_CSS = ${JSON.stringify(css)};\n`,
);

mkdirSync(path.join(relay, "dist"), { recursive: true });
await esbuild({
  entryPoints: [path.join(relay, "src/worker.ts")],
  outfile: path.join(relay, "dist/worker.js"),
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  legalComments: "none",
  logLevel: "warning",
});
const size = readFileSync(path.join(relay, "dist/worker.js")).length;
console.log(`relay/dist/worker.js: ${(size / 1024).toFixed(0)} KB (band page ${(js.length / 1024).toFixed(0)} KB + ${(css.length / 1024).toFixed(0)} KB css)`);
