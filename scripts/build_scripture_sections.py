"""Write `sidecar/auto_presenter/scripture/_sections.py` from the BSB's headings.

Run once (and again only to change the source):

    python3 scripts/build_scripture_sections.py [path/to/engbsb_usfm.zip]

Without a path it downloads https://ebible.org/Scriptures/engbsb_usfm.zip.
The Berean Standard Bible, headings included, is public domain (2023).

The table is where each section starts — `\\s1` headings, keyed by the
canonical USFM code and the chapter — so a verse can be offered with the
passage around it ("John 3:16" -> 3:16–21, 3:1–21) in any installed
translation. Only the boundaries and the heading text are kept.
"""

from __future__ import annotations

import io
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

URL = "https://ebible.org/Scriptures/engbsb_usfm.zip"
OUT = Path(__file__).resolve().parents[1] / "sidecar/auto_presenter/scripture/_sections.py"

_NOTE = re.compile(r"\\(f|x|fe)\s.*?\\\1\*")  # footnotes and cross references
_CHAR = re.compile(r"\\\+?[a-z]+\d*\*?\s?")  # any remaining character marker


def clean(title: str) -> str:
    return " ".join(_CHAR.sub("", _NOTE.sub("", title)).split())


def sections(usfm: str) -> tuple[str, dict[int, list[tuple[int, str]]]] | None:
    code = None
    chapter = 0
    pending: str | None = None
    out: dict[int, list[tuple[int, str]]] = {}
    for line in usfm.splitlines():
        line = line.strip()
        if line.startswith("\\id "):
            code = line.split()[1].upper()
        elif line.startswith("\\c "):
            chapter = int(line.split()[1])
        elif line.startswith("\\s1 "):
            pending = clean(line[4:])
        else:
            m = re.search(r"\\v (\d+)", line)
            if m and pending is not None and chapter:
                out.setdefault(chapter, []).append((int(m.group(1)), pending))
                pending = None
    return (code, out) if code else None


def main() -> None:
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
        data = urllib.request.urlopen(req, timeout=60).read()
    books: dict[str, dict[int, list[tuple[int, str]]]] = {}
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for name in sorted(z.namelist()):
            if not name.endswith((".usfm", ".SFM", ".sfm")):
                continue
            got = sections(z.read(name).decode("utf-8-sig"))
            if got and got[1]:
                books[got[0]] = got[1]

    lines = [
        '"""Where each section of the Bible starts: the Berean Standard Bible\'s',
        "headings (public domain), by canonical USFM code and chapter.",
        "",
        "Generated by scripts/build_scripture_sections.py — don't edit by hand.",
        "Used to offer a verse with the passage around it",
        '("John 3:16" -> 3:16–21, 3:1–21) in whatever translation is installed.',
        '"""',
        "",
        "SECTIONS: dict[str, dict[int, tuple[tuple[int, str], ...]]] = {",
    ]
    for code, chapters in books.items():
        lines.append(f"    {code!r}: {{")
        for chapter, starts in sorted(chapters.items()):
            lines.append(f"        {chapter}: {tuple(starts)!r},")
        lines.append("    },")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(len(s) for c in books.values() for s in c.values())
    print(f"wrote {OUT} ({len(books)} books, {total} sections)")


if __name__ == "__main__":
    main()
