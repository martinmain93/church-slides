"""Generate TypeScript types from Pydantic models.

Walks the protocol + library type modules, emits a single `.ts` file with
interfaces for every model. Committed to the repo so CI can flag drift.

Run via: pnpm codegen
"""

from __future__ import annotations

import sys
from pathlib import Path
from types import GenericAlias, UnionType
from typing import Any, Union, get_args, get_origin

from pydantic import BaseModel
from pydantic.fields import FieldInfo


REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "sidecar"))

OUTPUT_PATH = REPO_ROOT / "src" / "types" / "generated.ts"

HEADER = """// AUTO-GENERATED by shared/codegen.py — DO NOT EDIT BY HAND.
// Pydantic models in sidecar/auto_presenter/ are the source of truth.

/* eslint-disable */
"""


def collect_models() -> list[type[BaseModel]]:
    """Import the model modules and pull out every BaseModel subclass.

    Every model is rebuilt before it is returned, and that is load-bearing
    rather than defensive. `protocol.py` uses `from __future__ import
    annotations`, so every annotation is a string, and a model referring to an
    alias defined *later in the same file* — `StartAudioSessionRequest.ai_mode`
    is `AIMode`, declared 18 lines further down — cannot resolve it at class
    creation. Pydantic leaves the field unresolved, this generator sees no type
    to emit, and the TypeScript silently degrades to `unknown`. Three fields
    were shipping that way (`ai_mode`, `matcher_kind`, `tunables`): the
    frontend had no type safety on any of them, and nothing pointed at it.

    It also made `test_codegen.py` order-dependent, which is how it surfaced.
    Something later in a test session — any code that actually *validates* one
    of these messages — triggers the rebuild implicitly, after which this
    generator produces different (correct) output than it did cold. The test
    passed or failed on whether it happened to run before that.
    """
    from auto_presenter import protocol
    from auto_presenter.library import types as library_types

    _ = (library_types, protocol)

    seen: dict[str, type[BaseModel]] = {}
    for module in (library_types, protocol):
        for name in dir(module):
            obj = getattr(module, name)
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj is not BaseModel
                and obj.__module__.startswith("auto_presenter.")
                and not obj.__name__.startswith("_")
            ):
                seen[obj.__name__] = obj

    for model in seen.values():
        # `force=True` so a model Pydantic already considers complete is still
        # re-resolved against its module's finished namespace, and an explicit
        # namespace because the defining module — not this one — is where the
        # aliases live.
        model.model_rebuild(
            force=True,
            _types_namespace=vars(sys.modules[model.__module__]),
        )

    # Stable order: alphabetical
    return [seen[k] for k in sorted(seen)]


def collect_unions() -> list[tuple[str, list[str]]]:
    """Pull `ClientMessage` and `ServerMessage` discriminated unions from protocol.py.

    Returns [(name, [member_class_names])] sorted alphabetically by name.
    """
    from auto_presenter import protocol

    from typing import get_args

    unions: list[tuple[str, list[str]]] = []
    for name in ("ClientMessage", "ServerMessage"):
        annotation = getattr(protocol, name, None)
        if annotation is None:
            continue
        # Annotated[Union[...], Field(...)] — strip Annotated, then Union args.
        annotated_args = get_args(annotation)
        if not annotated_args:
            continue
        union_type = annotated_args[0]
        members = get_args(union_type)
        member_names = [m.__name__ for m in members if isinstance(m, type)]
        if member_names:
            unions.append((name, member_names))
    return sorted(unions, key=lambda x: x[0])


def emit_interface(model: type[BaseModel]) -> str:
    lines = [f"export interface {model.__name__} {{"]
    for field_name, field in model.model_fields.items():
        ts_type = python_to_ts(field.annotation, field)
        # `kind: Literal["x"] = "x"` defaults in Pydantic but should be required
        # on the wire — clients always send it.
        is_kind_literal = field_name == "kind" and ts_type.startswith('"')
        optional = "?" if not field.is_required() and not is_kind_literal else ""
        lines.append(f"  {field_name}{optional}: {ts_type};")
    lines.append("}")
    return "\n".join(lines)


def python_to_ts(annotation: Any, field: FieldInfo | None = None) -> str:
    if annotation is None or annotation is type(None):
        return "null"
    if annotation is str:
        return "string"
    if annotation is int or annotation is float:
        return "number"
    if annotation is bool:
        return "boolean"

    origin = get_origin(annotation)
    args = get_args(annotation)

    # Literal types
    from typing import Literal

    if origin is Literal:
        return " | ".join(_format_literal(a) for a in args)

    # Union and X | None — dedupe rendered types
    if origin in (Union, UnionType):
        rendered_parts: list[str] = []
        for a in args:
            piece = python_to_ts(a)
            if piece not in rendered_parts:
                rendered_parts.append(piece)
        return " | ".join(rendered_parts)

    # Annotated[X, Field(discriminator=...)] -> just the inner type
    if str(origin).startswith("typing.Annotated") or origin is None and args:
        return python_to_ts(args[0])

    # list[T]
    if origin in (list, tuple) or annotation is list:
        if not args:
            return "unknown[]"
        return f"{python_to_ts(args[0])}[]"

    # dict[K, V]
    if origin is dict:
        if len(args) == 2:
            return f"Record<{python_to_ts(args[0])}, {python_to_ts(args[1])}>"
        return "Record<string, unknown>"

    # datetime -> ISO string on the wire
    import datetime as _dt

    if annotation is _dt.datetime or annotation is _dt.date:
        return "string"

    # GenericAlias fallthrough
    if isinstance(annotation, GenericAlias):
        return python_to_ts(annotation.__origin__)

    # BaseModel subclasses -> their interface name
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation.__name__

    return "unknown"


def _format_literal(value: Any) -> str:
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    return str(value)


#: Models whose *default values* are emitted as a TS const, not just their
#: shape. A hand-kept mirror of a tuned default silently drifts: `tunables.ts`
#: pinned `lead_time_ms: 500` while a documented sweep had already moved the
#: Python default to 1500, and because the frontend sends tunables on every
#: session start, the stale copy won — the shipped app ran at 500 ms
#: (measured cost: displayed wrong-slide 0.273 -> 0.297, median lag 287 ms
#: worse). Every other field in that object still matched, which is exactly
#: what drift looks like. Generating the defaults removes the copy.
DEFAULTS_TO_EMIT = ("ParticleFilterTunables",)


def emit_defaults(model: type[BaseModel]) -> str:
    """A `DEFAULT_<NAME>` const carrying the model's own field defaults."""
    const = "DEFAULT_" + "".join(
        f"_{c}" if c.isupper() and i else c.upper()
        for i, c in enumerate(model.__name__)
    ).upper().replace("__", "_")
    lines = [f"export const {const}: {model.__name__} = {{"]
    for field_name, value in model().model_dump().items():
        lines.append(f"  {field_name}: {_format_literal(value)},")
    lines.append("};")
    return "\n".join(lines)


#: Requests the server answers with something other than the `<X>Response`
#: its name implies, or does not answer at all.
#:
#: `record_slide_change` is the interesting one: it is a *notification*, and
#: the server returns without sending anything. The client was calling
#: `request()` on it anyway, so every slide change in a service opened a
#: pending entry that sat for the full 5 s timeout and then rejected into a
#: swallowed `.catch()`. Typing it `never` makes that a compile error and
#: points the caller at `notify()`.
REPLY_OVERRIDES = {
    "ping": "PongMessage",
    "record_slide_change": "never",
    "live_scripture": "never",
}


def emit_reply_map(models: list[type[BaseModel]]) -> str:
    """`ResponseForKind` — which reply each request kind comes back with.

    Derived rather than hand-written, because a hand-written copy is what the
    `as unknown as Reply` casts at each call site effectively were: a claim
    about the server that nothing checked. The convention holds for every
    request (`<X>Request` -> `<X>Response`, else an empty `PongMessage` ack),
    and was verified against what the handlers actually send before being
    relied on here; `REPLY_OVERRIDES` carries the exceptions.
    """
    names = {m.__name__ for m in models}
    by_name = {m.__name__: m for m in models}
    client = [m for m in models if m.__name__ in _client_message_members()]
    lines = ["export interface ResponseForKind {"]
    for model in client:
        kind = by_name[model.__name__].model_fields["kind"].default
        reply = REPLY_OVERRIDES.get(kind)
        if reply is None:
            candidate = model.__name__.replace("Request", "Response")
            reply = candidate if candidate in names else "PongMessage"
        lines.append(f"  {kind}: {reply};")
    lines.append("}")
    return "\n".join(lines)


def _client_message_members() -> set[str]:
    from auto_presenter import protocol

    from typing import get_args

    return {m.__name__ for m in get_args(get_args(protocol.ClientMessage)[0])}


def render() -> str:
    """The full file contents.

    Single source of the assembly order, because `test_codegen.py`'s
    drift check needs the same bytes: when the test rebuilt the body
    itself, adding a section here made it fail until the test was taught
    the new shape — the very duplication this generator exists to remove.
    """
    models = collect_models()
    unions = collect_unions()
    parts: list[str] = [HEADER]
    for model in models:
        parts.append(emit_interface(model))
    for name, members in unions:
        parts.append(f"export type {name} = {' | '.join(members)};")
    by_name = {m.__name__: m for m in models}
    for name in DEFAULTS_TO_EMIT:
        model = by_name.get(name)
        if model is None:
            raise LookupError(f"{name} is in DEFAULTS_TO_EMIT but was not collected")
        parts.append(emit_defaults(model))
    parts.append(emit_reply_map(models))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    body = render()
    models = collect_models()
    unions = collect_unions()

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    if OUTPUT_PATH.exists() and OUTPUT_PATH.read_text(encoding="utf-8") == body:
        print(f"codegen: {OUTPUT_PATH} already up to date")
        return 0

    OUTPUT_PATH.write_text(body, encoding="utf-8")
    print(f"codegen: wrote {OUTPUT_PATH} ({len(models)} types, {len(unions)} unions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
